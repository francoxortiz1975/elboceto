// Runs the scheduler tests (locks, area hours, habits, rollover, server job) and checks that api/rollover.js is up to date.
// Usage: npm run test:scheduler
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const tmp = mkdtempSync(join(tmpdir(), 'boceto-test-'));
const esbuild = (entry, out, extra = []) => execFileSync('node_modules/.bin/esbuild', [entry, '--bundle', '--platform=node', '--format=esm', `--outfile=${out}`, '--log-level=error', ...extra], { stdio: 'inherit' });
let failed = 0;
for (const t of ['scheduler-locks', 'scheduler-windows', 'habits', 'rollover', 'rollover-server', 'iris']) {
  const out = join(tmp, `${t}.mjs`);
  esbuild(`mcp/test/${t}.mjs`, out);
  const text = execFileSync('node', [out], { encoding: 'utf8' });
  const fails = text.split('\n').filter((l) => l.startsWith('FAIL'));
  console.log(`${fails.length ? 'FAIL' : 'ok  '} ${t}: ${text.split('\n').filter((l) => l.startsWith('ok')).length} ok${fails.length ? `\n   ${fails.join('\n   ')}` : ''}`);
  failed += fails.length;
}
// the committed bundle must match its source
const fresh = join(tmp, 'rollover.js');
esbuild('server/rollover.mjs', fresh, ['--banner:js=// GENERATED by npm run api:build from server/rollover.mjs and src/lib. Do not edit.']);
const same = readFileSync(fresh, 'utf8') === readFileSync('api/rollover.js', 'utf8');
console.log(`${same ? 'ok  ' : 'FAIL'} api/rollover.js is ${same ? 'up to date' : 'OUT OF DATE: run npm run api:build'}`);
if (!same) failed += 1;
process.exit(failed ? 1 : 0);
